#!/usr/bin/env python3
"""
SEATL benchmark harness — run THIS on your own machine (the one with the
real CPU your paper's methodology section names, e.g. i7-13700HX), not on
any sandboxed/cloud machine. Thread-count comparisons are meaningless on
a single-core box.

Usage:
    cd SEATL
    g++ -std=c++17 -O3 -fopenmp seatl_solver.cpp seatl_solver_xl.cpp seatl_cli_xl.cpp -o seatl_cli_xl
    python3 run_benchmarks.py

Output:
    seatl_benchmark_results.md   (tables 1, 3, 4 — real data)
                                  (table 2 has a placeholder column for your
                                   existing 11-layer numbers — see note in file)
    seatl_benchmark_raw.csv      (every trial, unaggregated, for your own audit)
"""

import subprocess, re, statistics, csv, sys, os
from pathlib import Path

# Resolve the binary cross-platform: g++ on Windows (MinGW) emits seatl_cli_xl.exe,
# on Linux/macOS it's seatl_cli_xl. Prefer whichever actually exists next to us.
def _resolve_bin():
    base = Path(__file__).parent
    for name in ("seatl_cli_xl", "seatl_cli_xl.exe"):
        p = base / name
        if p.exists():
            return str(p)
    return str(base / "seatl_cli_xl")

BIN = _resolve_bin()
SIZES = [(7,7),(10,10),(12,12),(12,15),(15,15),(18,18),(20,20),(22,22),(25,25)]
THREAD_CONFIGS = [1, 8]
TRIALS = 5
BUDGET = 150  # seconds, raise this if you expect timeouts at K_{25,25}

RE_TIME   = re.compile(r"Time:\s*([\d.]+)\s*ms")
RE_STATUS = re.compile(r"Status:\s*(.+)")
RE_PART   = re.compile(r"Partitions tested:\s*(\d+)\s*\(L1 pruned:\s*(\d+),\s*L2 pruned:\s*(\d+)\)")
RE_GREEDY = re.compile(r"Layer 3 greedy successes:\s*(\d+)")
RE_DFS    = re.compile(r"DFS invocations:\s*(\d+)")
RE_MEMO   = re.compile(r"Memo hits:\s*(\d+)")
RE_A      = re.compile(r"Solution \(a = (\d+)")
RE_WEIGHT = re.compile(r"weight=\s*(\d+)")

def run_once(m, n, threads):
    cmd = [BIN, str(m), str(n), "-t", str(BUDGET), "-j", str(threads), "--no-matrix"]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=BUDGET + 30).stdout
    except subprocess.TimeoutExpired:
        return None

    t = RE_TIME.search(out)
    status = RE_STATUS.search(out)
    part = RE_PART.search(out)
    greedy = RE_GREEDY.search(out)
    dfs = RE_DFS.search(out)
    memo = RE_MEMO.search(out)
    a_match = RE_A.search(out)

    if not t or not status:
        return None

    solved = "No solution found" not in out
    verified = False
    if solved and a_match:
        a = int(a_match.group(1))
        mn = m * n
        weights = sorted(int(w) for w in RE_WEIGHT.findall(out))
        verified = (len(weights) == mn and weights[0] == a and weights[-1] == a + mn - 1
                    and len(set(weights)) == mn)

    return {
        "m": m, "n": n, "threads": threads,
        "time_ms": float(t.group(1)),
        "status": status.group(1).strip(),
        "solved": solved,
        "verified": verified,
        "partitions_tested": int(part.group(1)) if part else None,
        "l1_pruned": int(part.group(2)) if part else None,
        "l2_pruned": int(part.group(3)) if part else None,
        "greedy_successes": int(greedy.group(1)) if greedy else None,
        "dfs_invocations": int(dfs.group(1)) if dfs else None,
        "memo_hits": int(memo.group(1)) if memo else None,
    }

def median(vals):
    vals = [v for v in vals if v is not None]
    return statistics.median(vals) if vals else None

def main():
    if not Path(BIN).exists():
        print(f"ERROR: {BIN} not found. Compile it first (see README), "
              f"then run this script from inside the SEATL/ folder.")
        sys.exit(1)

    all_rows = []
    results = {}  # (m,n,threads) -> list of trial dicts

    for (m, n) in SIZES:
        for threads in THREAD_CONFIGS:
            key = (m, n, threads)
            trials = []
            print(f"Running K_{{{m},{n}}} @ {threads} thread(s) x{TRIALS} trials...", flush=True)
            for t in range(TRIALS):
                r = run_once(m, n, threads)
                if r:
                    trials.append(r)
                    all_rows.append(r)
                    print(f"  trial {t+1}: {r['time_ms']:.1f} ms, "
                          f"solved={r['solved']}, verified={r['verified']}", flush=True)
                else:
                    print(f"  trial {t+1}: TIMEOUT/no parse", flush=True)
            results[key] = trials

    # ---- write raw CSV ----
    if all_rows:
        with open("seatl_benchmark_raw.csv", "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(all_rows[0].keys()))
            w.writeheader()
            w.writerows(all_rows)

    # ---- build markdown ----
    md = []
    md.append("# SEATL Benchmark Results\n")
    md.append(f"_Generated by run_benchmarks.py — {TRIALS} trials per cell, "
              f"{BUDGET}s budget per run._\n")
    md.append("**Run this script's header comment block to record your actual "
              "CPU model, compiler, and flags here before using these numbers "
              "in the paper.**\n")

    # Table 1: Parallel speedup
    md.append("\n## Table 1 — Parallel Speedup vs. Graph Size\n")
    md.append("| Graph | m·n | T1 median (ms) | T8 median (ms) | Speedup (T1/T8) |")
    md.append("|---|---|---|---|---|")
    for (m, n) in SIZES:
        t1 = median([r["time_ms"] for r in results[(m,n,1)] if r["solved"]])
        t8 = median([r["time_ms"] for r in results[(m,n,8)] if r["solved"]])
        speedup = f"{t1/t8:.2f}×" if (t1 and t8) else "N/A"
        t1s = f"{t1:.2f}" if t1 else "TIMEOUT"
        t8s = f"{t8:.2f}" if t8 else "TIMEOUT"
        md.append(f"| K_{{{m},{n}}} | {m*n} | {t1s} | {t8s} | {speedup} |")

    # Table 2: Solve time (11-layer column left as placeholder)
    md.append("\n## Table 2 — Solve Time vs. Graph Size\n")
    md.append("> NOTE: the '11-layer' column is NOT regenerated here — your current "
              "main() always runs the XL solver for m·n > 30, which covers every size "
              "below. Carry over your existing 11-layer numbers from your prior benchmark "
              "table for this column; only the two XL columns are fresh data from this run.\n")
    md.append("| Graph | m·n | 11-layer (ms, from prior data) | 12-layer 1 thread (ms) | 12-layer 8 threads (ms) |")
    md.append("|---|---|---|---|---|")
    for (m, n) in SIZES:
        t1 = median([r["time_ms"] for r in results[(m,n,1)] if r["solved"]])
        t8 = median([r["time_ms"] for r in results[(m,n,8)] if r["solved"]])
        t1s = f"{t1:.2f}" if t1 else "TIMEOUT"
        t8s = f"{t8:.2f}" if t8 else "TIMEOUT"
        md.append(f"| K_{{{m},{n}}} | {m*n} | _carry over_ | {t1s} | {t8s} |")

    # Table 3: Reliability
    md.append("\n## Table 3 — Reliability (Solved/Verified per Trial)\n")
    md.append("| Graph | Threads | Trials | Solved | Verified correct | Solve rate |")
    md.append("|---|---|---|---|---|---|")
    for (m, n) in SIZES:
        for threads in THREAD_CONFIGS:
            trials = results[(m,n,threads)]
            solved = sum(1 for r in trials if r["solved"])
            verified = sum(1 for r in trials if r["verified"])
            rate = f"{100*solved/TRIALS:.0f}%" if TRIALS else "N/A"
            md.append(f"| K_{{{m},{n}}} | {threads} | {TRIALS} | {solved} | {verified} | {rate} |")

    # Table 4: Search effort
    md.append("\n## Table 4 — Search Effort vs. Graph Size (1 thread)\n")
    md.append("| Graph | Partitions tested (median) | L1 pruned | L2 pruned | Greedy successes | DFS invocations | Memo hits |")
    md.append("|---|---|---|---|---|---|---|")
    for (m, n) in SIZES:
        trials = results[(m,n,1)]
        pt = median([r["partitions_tested"] for r in trials])
        l1 = median([r["l1_pruned"] for r in trials])
        l2 = median([r["l2_pruned"] for r in trials])
        gs = median([r["greedy_successes"] for r in trials])
        df = median([r["dfs_invocations"] for r in trials])
        mh = median([r["memo_hits"] for r in trials])
        row = [pt, l1, l2, gs, df, mh]
        row = [f"{int(v)}" if v is not None else "N/A" for v in row]
        md.append(f"| K_{{{m},{n}}} | " + " | ".join(row) + " |")

    md.append("\n## Table 5 — Threshold Crossover\n")
    md.append("Not generated by this script. Your current `main()` always uses "
              "the XL solver path for m·n > 30 (every benchmarked size qualifies), "
              "and there's no CLI flag to force the standard 11-layer solver above "
              "threshold. To get this table you'd need to temporarily set "
              "`skip_enumeration_xl = false` in `ConfigXL` (seatl_solver_xl.hpp, line "
              "~40), recompile to a second binary, and re-run on small/mid instances. "
              "Happy to write that variant if you want this table — let me know.\n")

    Path("seatl_benchmark_results.md").write_text("\n".join(md), encoding="utf-8")
    print("\nWrote seatl_benchmark_results.md and seatl_benchmark_raw.csv")

if __name__ == "__main__":
    main()
